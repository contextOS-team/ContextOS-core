"""Embedding model mapping to public.embeddings table."""

import uuid
from datetime import datetime

from pgvector.sqlalchemy import Vector
from sqlalchemy import Column, UniqueConstraint
from sqlalchemy import text as sa_text
from sqlalchemy.dialects.postgresql import JSONB
from sqlmodel import Field, SQLModel


class Embedding(SQLModel, table=True):
    """Vector embedding record mapping to public.embeddings table.

    Stores 768-dimensional embeddings generated by Google text-embedding-004
    for semantic search via pgvector HNSW index.

    Does NOT inherit BaseModel because the table has no updated_at column.
    """

    __tablename__ = "embeddings"
    __table_args__ = (
        UniqueConstraint("source_type", "source_id", name="embeddings_source_type_source_id_key"),
    )

    id: uuid.UUID = Field(default_factory=uuid.uuid4, primary_key=True)
    workspace_id: uuid.UUID = Field(foreign_key="workspaces.id", nullable=False)
    source_type: str = Field(nullable=False)
    source_id: uuid.UUID = Field(nullable=False)
    content_hash: str = Field(nullable=False)
    embedding: list[float] = Field(
        sa_column=Column(Vector(768), nullable=False),
    )
    metadata_: dict = Field(
        default_factory=dict,
        sa_column=Column("metadata", JSONB, nullable=True, server_default=sa_text("'{}'")),
    )
    deleted_at: datetime | None = Field(default=None)
    created_at: datetime | None = Field(
        default=None,
        nullable=False,
        sa_column_kwargs={"server_default": sa_text("now()")},
    )
